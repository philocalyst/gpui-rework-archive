#!/usr/bin/env python3
"""Add idempotent generated example links to public Rust declarations."""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import re
import sys
import tomllib

ROOT = Path(__file__).resolve().parents[2]
BEGIN, END = "// docs:examples:begin", "// docs:examples:end"


def example_markdown(symbol: str, rows: list[tuple[str, str, str, str]]) -> str:
    # Raw HTML comments survive rustdoc rendering. The local postprocessor can
    # replace exactly this block, while docs.rs keeps the ordinary links.
    return (f"\n\n<!-- gpui-walkthroughs:begin {symbol} -->\n\nWalkthroughs:\n\n" +
            "\n".join(f"- [{title}: {step_title}](https://gpui-ce.github.io/examples/{slug}/#{step})"
                      for title, slug, step, step_title in sorted(set(rows))) +
            f"\n\n<!-- gpui-walkthroughs:end {symbol} -->\n")


def safe_symbol(symbol: str) -> str:
    # Preserve case so `gpui::Div` and `gpui::div` cannot collide.
    base = re.sub(r"[^a-zA-Z0-9]+", "-", symbol).strip("-")
    # macOS commonly uses a case-insensitive filesystem; disambiguate symbols
    # such as `Div` and `div` while keeping ordinary names readable.
    return base + ("-" + hashlib.sha1(symbol.encode()).hexdigest()[:8] if any(c.isupper() for c in symbol) else "")


def generated_block(path: Path, source: Path, symbol: str) -> str:
    crate_root = next((p for p in source.parents if (p / "Cargo.toml").is_file()), None)
    if crate_root is None:
        raise ValueError(f"{source}: cannot locate crate root")
    target = crate_root / "src" / "docs" / "examples" / f"{safe_symbol(symbol)}.md"
    # Callers create generated files only in write mode; this helper is also
    # used by --check, which must be entirely side-effect free.
    include = Path(os.path.relpath(target, path.parent)).as_posix()
    return f'{BEGIN}\n#[doc = include_str!("{include}")]\n{END}'


def sync(root: Path, check: bool = False) -> list[str]:
    metadata = root / "site" / "examples.toml"
    if not metadata.is_file(): return [f"missing {metadata}"]
    data = tomllib.loads(metadata.read_text(encoding="utf-8"))
    source_for: dict[str, Path] = {}
    uses: dict[str, list[tuple[str, str, str, str]]] = {}
    for item in data.get("examples", []):
        source = root / item["source"]
        for symbol in item.get("apis", []): source_for[symbol] = source
    # Also derive symbols from parsed steps, so metadata remains declarative.
    sys.path.insert(0, str(Path(__file__).parent))
    from parser import parse_source
    for item in data.get("examples", []):
        source = root / item["source"]
        for step in parse_source(source, catalog=data.get("api", {})):
            for symbol in step.api:
                source_for[symbol] = source
                uses.setdefault(symbol, []).append((item["title"], item["slug"], step.slug, step.title))
    errors = []
    prepared_outputs: dict[Path, str] = {}
    processed_sources: set[Path] = set()
    cleaned_sources: set[Path] = set()
    # A few style helpers are generated by a proc macro rather than written as
    # Rust items. Keep their docs at the call site so rustdoc can still attach
    # the generated attribute to the selected method.
    macro_symbols = {
        symbol: api for symbol, api in data.get("api", {}).items()
        if api.get("declaration") in {"w;", "min_w;"}
    }
    macro_by_source: dict[Path, list[tuple[str, dict]]] = {}
    for symbol, api in macro_symbols.items():
        macro_by_source.setdefault(root / api.get("source", ""), []).append((symbol, api))
    for source, entries in macro_by_source.items():
        if not source.is_file():
            errors.append(f"{source}: source/declaration metadata is incomplete")
            continue
        text = source.read_text(encoding="utf-8").replace("\r\n", "\n")
        # Remove only our previous style-helper wrapper. Other generated docs
        # on the trait remain untouched.
        docs = []
        for symbol, _api in sorted(entries):
            rows = uses.get(symbol, [])
            if not rows:
                continue
            doc_file = next(p for p in source.parents if (p / "Cargo.toml").is_file()) / "src" / "docs" / "examples" / f"{safe_symbol(symbol)}.md"
            doc_text = example_markdown(symbol, rows)
            if check:
                if not doc_file.is_file() or doc_file.read_text(encoding="utf-8") != doc_text:
                    errors.append(f"stale generated example doc: {doc_file}")
            else:
                doc_file.parent.mkdir(parents=True, exist_ok=True)
                doc_file.write_text(doc_text, encoding="utf-8", newline="\n")
            include = Path(os.path.relpath(doc_file, source.parent)).as_posix()
            method = _api["declaration"][:-1]
            docs.append(f'        {method}: #[doc = include_str!("{include}")],')
        if docs:
            block = "// docs:examples:begin\n" + "gpui_macros::style_helpers! {\n    docs {\n" + "\n".join(docs) + "\n    }\n}\n// docs:examples:end\n"
            # These helpers are emitted inside the Styled trait. Keep the
            # generated wrapper at the trait body's indentation so rustfmt
            # does not make a freshly synced source appear stale.
            block = "\n".join("    " + line for line in block.splitlines()) + "\n"
            # The call is intentionally replaced as one unit, making repeated
            # syncs deterministic and allowing removed methods to disappear.
            call = re.compile(
                r"(?ms)^\s*// docs:examples:begin\n\s*gpui_macros::style_helpers!\s*\{.*?^\s*// docs:examples:end\n?"
                r"|^\s*gpui_macros::style_helpers!\s*(?:\(\)|\{.*?\})\s*;?"
            )
            if not call.search(text):
                errors.append(f"{source}: missing style_helpers! invocation")
            else:
                text = call.sub(block.rstrip("\n") + "\n", text, count=1)
        else:
            text = re.sub(r"(?ms)^\s*// docs:examples:begin\n\s*gpui_macros::style_helpers!\s*\{.*?^\s*// docs:examples:end\n?", "    gpui_macros::style_helpers!();\n", text)
        prepared_outputs[source] = text.rstrip() + "\n"
        processed_sources.add(source)
    handled_macro_symbols = set(macro_symbols)
    for symbol, api in data.get("api", {}).items():
        if symbol in handled_macro_symbols:
            continue
        source = root / api.get("source", source_for.get(symbol, ""))
        declaration = api.get("declaration", "")
        if not source.is_file() or not declaration:
            errors.append(f"{symbol}: source/declaration metadata is incomplete")
            continue
        lines = (prepared_outputs[source].splitlines() if source in prepared_outputs
                 else source.read_text(encoding="utf-8").replace("\r\n", "\n").splitlines())
        # Remove earlier item blocks once per source. A style-helper wrapper is
        # itself generated code and must remain while direct methods are added.
        if source not in cleaned_sources:
            clean: list[str] = []
            i = 0
            while i < len(lines):
                if lines[i].strip() != BEGIN:
                    clean.append(lines[i]); i += 1; continue
                end = next((j for j in range(i + 1, len(lines)) if lines[j].strip() == END), None)
                if end is None:
                    errors.append(f"{source}: unterminated generated example block")
                    clean.extend(lines[i:]); break
                block = lines[i:end + 1]
                if any("style_helpers!" in line for line in block):
                    clean.extend(block)
                i = end + 1
            lines = clean
            cleaned_sources.add(source)
        clean = lines
        needle = declaration.strip()
        token = re.compile(re.escape(needle) if needle.endswith(("<", "(", "{")) else re.escape(needle) + r"(?![A-Za-z0-9_])")
        matches = [i for i, line in enumerate(clean) if token.search(line)]
        if len(matches) != 1:
            errors.append(f"{source}: expected one declaration containing {declaration!r}, found {len(matches)}")
            continue
        crate_root = next(p for p in source.parents if (p / "Cargo.toml").is_file())
        doc_file = crate_root / "src" / "docs" / "examples" / f"{safe_symbol(symbol)}.md"
        rows = uses.get(symbol, [])
        if not rows:
            prepared_outputs[source] = "\n".join(clean).rstrip() + "\n"
            processed_sources.add(source)
            continue
        if not check: doc_file.parent.mkdir(parents=True, exist_ok=True)
        doc_text = example_markdown(symbol, rows)
        if check:
            if not doc_file.is_file() or doc_file.read_text(encoding="utf-8") != doc_text:
                errors.append(f"stale generated example doc: {doc_file}")
        else:
            doc_file.write_text(doc_text, encoding="utf-8", newline="\n")
        line_no = matches[0]
        indent = clean[line_no][:len(clean[line_no]) - len(clean[line_no].lstrip())]
        block = [indent + line for line in generated_block(source, source, symbol).splitlines()]
        result = clean[:line_no] + block + clean[line_no:]
        output = "\n".join(result).rstrip() + "\n"
        prepared_outputs[source] = output
        processed_sources.add(source)
    for source, output in prepared_outputs.items():
        if check:
            if source.read_text(encoding="utf-8").replace("\r\n", "\n") != output:
                errors.append(f"stale generated links: {source}")
        else:
            source.write_text(output, encoding="utf-8", newline="\n")
    # Remove bounded attributes for API symbols that no longer exist in the
    # registry. Only files containing our markers are candidates; authored
    # documentation and unrelated Rust files are never touched.
    valid_stems = {safe_symbol(symbol) for symbol in uses}
    for source in root.glob("crates/**/*.rs"):
        text = source.read_text(encoding="utf-8", errors="ignore")
        if BEGIN not in text and END not in text:
            continue
        lines = text.replace("\r\n", "\n").splitlines()
        result, i, changed = [], 0, False
        while i < len(lines):
            if lines[i].strip() != BEGIN:
                result.append(lines[i]); i += 1; continue
            end = next((j for j in range(i + 1, len(lines)) if lines[j].strip() == END), None)
            if end is None:
                errors.append(f"{source}: unterminated generated example block"); result.extend(lines[i:]); break
            block = lines[i:end + 1]
            include = next((line for line in block if "include_str!" in line), "")
            stem = Path(re.search(r'include_str!\("([^"]+)', include).group(1)).stem if re.search(r'include_str!\("([^"]+)', include) else ""
            if stem not in valid_stems:
                changed = True; i = end + 1; continue
            result.extend(block); i = end + 1
        output = "\n".join(result).rstrip() + "\n"
        if changed:
            if check:
                errors.append(f"stale generated links: {source}")
            else:
                source.write_text(output, encoding="utf-8", newline="\n")
    # Remove only files carrying the generator's unmistakable first line.
    for crate_src in root.glob("crates/*/src/docs/examples"):
        if not crate_src.is_dir():
            continue
        for stale in crate_src.glob("*.md"):
            text = stale.read_text(encoding="utf-8", errors="ignore")
            if (text.startswith("Examples for `") or text.lstrip().startswith("<!-- gpui-walkthroughs:begin ")) and stale.stem not in valid_stems:
                if check: errors.append(f"stale generated example doc: {stale}")
                else: stale.unlink()
    return errors


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    errors = sync(ROOT, args.check)
    if errors:
        print("\n".join(errors), file=sys.stderr); return 1
    print("documentation links are up to date" if args.check else "synced documentation links")
    return 0


if __name__ == "__main__": raise SystemExit(main())
