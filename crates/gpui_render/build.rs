#[path = "src/shaders/mod.rs"]
mod shaders;

use std::{collections::BTreeSet, env, fmt::Write as _, fs, path::PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=src/shaders");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR must be set"));
    let base = shader_source("gpui_base.wgsl", &shaders::base::WGSL_SOURCE);
    let subpixel = shader_source("gpui_subpixel.wgsl", &shaders::subpixel_sprite::WGSL_SOURCE);
    let subpixel_dual_source = format!("enable dual_source_blending;\n{subpixel}");

    validate_shader("gpui_base.wgsl", &base);
    validate_current_shader("gpui_subpixel_dual_source.wgsl", &subpixel_dual_source);

    write_shader(&out_dir, "gpui_base.wgsl", &base);
    write_shader(
        &out_dir,
        "gpui_subpixel_dual_source.wgsl",
        &subpixel_dual_source,
    );

    let quad = shader_source("quad interface", &shaders::quad::WGSL_SOURCE);
    let polychrome = shader_source(
        "polychrome sprite interface",
        &shaders::polychrome_sprite::WGSL_SOURCE,
    );
    let surface = shader_source("surface interface", &shaders::surface::WGSL_SOURCE);
    let blur = shader_source("blur interface", &shaders::blur::WGSL_SOURCE);
    let layouts = [
        ("GLOBAL_BINDINGS", base.as_str(), shaders::interface::GLOBAL_BIND_GROUP),
        ("INSTANCE_BINDINGS", quad.as_str(), shaders::interface::DATA_BIND_GROUP),
        (
            "TEXTURED_INSTANCE_BINDINGS",
            polychrome.as_str(),
            shaders::interface::DATA_BIND_GROUP,
        ),
        ("SURFACE_BINDINGS", surface.as_str(), shaders::interface::DATA_BIND_GROUP),
        ("BLUR_BINDINGS", blur.as_str(), shaders::interface::DATA_BIND_GROUP),
    ];
    write_interface(&out_dir, &layouts);
    write_native_shaders(&out_dir);
}

fn shader_source(name: &str, source: &wgsl_rs::Source) -> String {
    source
        .wgsl_source()
        .unwrap_or_else(|error| panic!("failed to generate {name}: {error}"))
}

fn write_shader(out_dir: &std::path::Path, name: &str, source: &str) {
    fs::write(out_dir.join(name), source).unwrap_or_else(|error| {
        panic!("failed to write generated shader {name}: {error}");
    });
}

fn validate_shader(name: &str, source: &str) {
    validate_current_shader(name, source);
    validate_previous_shader(name, source);
}

fn validate_current_shader(name: &str, source: &str) {
    let module = naga::front::wgsl::parse_str(source)
        .unwrap_or_else(|error| panic!("current Naga failed to parse {name}: {error}"));
    naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|error| panic!("current Naga failed to validate {name}: {error}"));
}

fn validate_previous_shader(name: &str, source: &str) {
    let module = naga_old::front::wgsl::parse_str(source)
        .unwrap_or_else(|error| panic!("previous Naga failed to parse {name}: {error}"));
    naga_old::valid::Validator::new(
        naga_old::valid::ValidationFlags::all(),
        naga_old::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|error| panic!("previous Naga failed to validate {name}: {error}"));
}

fn write_interface(
    out_dir: &std::path::Path,
    layouts: &[(&str, &str, u32)],
) {
    let mut generated = String::from("// @generated by build.rs; do not edit.\n");
    for &(constant, source, group) in layouts {
        validate_shader(constant, source);
        write_bindings(&mut generated, constant, source, group);
    }
    fs::write(out_dir.join("shader_interface.rs"), generated)
        .expect("failed to write generated shader interface");
}

fn write_bindings(generated: &mut String, constant: &str, source: &str, group: u32) {
    let module = naga::front::wgsl::parse_str(source)
        .unwrap_or_else(|error| panic!("failed to parse {constant}: {error}"));
    let info = naga::valid::Validator::new(
        naga::valid::ValidationFlags::all(),
        naga::valid::Capabilities::all(),
    )
    .validate(&module)
    .unwrap_or_else(|error| panic!("failed to validate {constant}: {error}"));
    let mut layouter = naga::proc::Layouter::default();
    layouter
        .update(module.to_ctx())
        .unwrap_or_else(|error| panic!("failed to lay out {constant}: {error}"));

    let mut bindings = module
        .global_variables
        .iter()
        .filter_map(|(handle, variable)| {
            let binding = variable.binding.as_ref()?;
            (binding.group == group).then_some((handle, variable, binding.binding))
        })
        .collect::<Vec<_>>();
    bindings.sort_by_key(|(_, _, binding)| *binding);
    let mut seen = BTreeSet::new();

    writeln!(
        generated,
        "pub const {constant}: &[GeneratedBinding] = &["
    )
    .unwrap();
    for (handle, variable, binding) in bindings {
        assert!(
            seen.insert(binding),
            "duplicate binding {group}:{binding} while generating {constant}"
        );
        let visibility = module
            .entry_points
            .iter()
            .enumerate()
            .filter(|(index, _)| !info.get_entry_point(*index)[handle].is_empty())
            .fold(0, |stages, (_, entry)| {
                stages
                    | match entry.stage {
                        naga::ShaderStage::Vertex => 1,
                        naga::ShaderStage::Fragment => 2,
                        naga::ShaderStage::Compute => 4,
                        stage => panic!("unsupported shader stage {stage:?} in {constant}"),
                    }
            });
        assert_ne!(visibility, 0, "binding {group}:{binding} is unused in {constant}");
        let kind = binding_kind(&module, &layouter, variable);
        writeln!(
            generated,
            "    GeneratedBinding {{ binding: {binding}, visibility: {visibility}, kind: {kind} }},"
        )
        .unwrap();
    }
    generated.push_str("];\n");
}

fn binding_kind(
    module: &naga::Module,
    layouter: &naga::proc::Layouter,
    variable: &naga::GlobalVariable,
) -> String {
    match variable.space {
        naga::AddressSpace::Uniform => format!(
            "GeneratedBindingKind::Uniform({})",
            layouter[variable.ty].size
        ),
        naga::AddressSpace::Storage { access } => {
            assert!(
                !access.contains(naga::StorageAccess::STORE),
                "writable shader storage is not supported by the generated interface"
            );
            format!(
                "GeneratedBindingKind::StorageRead({})",
                layouter[variable.ty].size
            )
        }
        naga::AddressSpace::Handle => match module.types[variable.ty].inner {
            naga::TypeInner::Image {
                dim: naga::ImageDimension::D2,
                arrayed: false,
                class:
                    naga::ImageClass::Sampled {
                        kind: naga::ScalarKind::Float,
                        multi: false,
                    },
            } => "GeneratedBindingKind::Texture2dFloat".into(),
            naga::TypeInner::Sampler { comparison: false } => {
                "GeneratedBindingKind::FilteringSampler".into()
            }
            ref ty => panic!("unsupported shader resource type {ty:?}"),
        },
        space => panic!("unsupported shader resource address space {space:?}"),
    }
}

fn write_native_shaders(out_dir: &std::path::Path) {
    use shaders::interface::*;

    let modules = [
        (QUADS, &shaders::quad::WGSL_SOURCE, false),
        (SHADOWS, &shaders::shadow::WGSL_SOURCE, false),
        (
            PATH_RASTERIZATION,
            &shaders::path_rasterization::WGSL_SOURCE,
            false,
        ),
        (PATHS, &shaders::path::WGSL_SOURCE, false),
        (UNDERLINES, &shaders::underline::WGSL_SOURCE, false),
        (
            MONOCHROME_SPRITES,
            &shaders::monochrome_sprite::WGSL_SOURCE,
            false,
        ),
        (
            SUBPIXEL_SPRITES,
            &shaders::subpixel_sprite::WGSL_SOURCE,
            true,
        ),
        (
            POLYCHROME_SPRITES,
            &shaders::polychrome_sprite::WGSL_SOURCE,
            false,
        ),
        (SURFACES, &shaders::surface::WGSL_SOURCE, false),
        (BLUR_DOWNSAMPLE, &shaders::blur::WGSL_SOURCE, false),
        (BLUR, &shaders::blur::WGSL_SOURCE, false),
        (BLUR_COMPOSITE, &shaders::blur::WGSL_SOURCE, false),
    ];
    let mut generated = String::from("// @generated by build.rs; do not edit.\n");
    generated.push_str("pub const NATIVE_SHADERS: &[NativeShader] = &[\n");

    for (pipeline, source, dual_source) in modules {
        let mut wgsl = shader_source(pipeline.label, source);
        if dual_source {
            wgsl = native_dual_source_wgsl(wgsl);
        }
        validate_shader(pipeline.label, &wgsl);
        let module = naga_old::front::wgsl::parse_str(&wgsl)
            .unwrap_or_else(|error| panic!("failed to parse {}: {error}", pipeline.label));
        let info = naga_old::valid::Validator::new(
            naga_old::valid::ValidationFlags::all(),
            naga_old::valid::Capabilities::all(),
        )
        .validate(&module)
        .unwrap_or_else(|error| panic!("failed to validate {}: {error}", pipeline.label));

        let hlsl = write_hlsl(&module, &info, pipeline.label);
        let msl = write_msl(&module, &info, pipeline.label);
        let hlsl_name = format!("{}.hlsl", pipeline.label);
        let msl_name = format!("{}.metal", pipeline.label);
        write_shader(out_dir, &hlsl_name, &hlsl);
        write_shader(out_dir, &msl_name, &msl);
        writeln!(
            generated,
            "    NativeShader {{ label: {:?}, vertex_entry: {:?}, fragment_entry: {:?}, hlsl: include_str!(concat!(env!(\"OUT_DIR\"), {:?})), msl: include_str!(concat!(env!(\"OUT_DIR\"), {:?})) }},",
            pipeline.label,
            pipeline.vertex_entry,
            pipeline.fragment_entry,
            format!("/{hlsl_name}"),
            format!("/{msl_name}"),
        )
        .unwrap();
    }
    generated.push_str("];\n");
    fs::write(out_dir.join("native_shaders.rs"), generated)
        .expect("failed to write generated native shader table");
}

fn native_dual_source_wgsl(source: String) -> String {
    source
        .replace("@location(0) @blend_src(0)", "@location(0)")
        .replace("@location(0) @blend_src(1)", "@location(1)")
}

fn write_hlsl(
    module: &naga_old::Module,
    info: &naga_old::valid::ModuleInfo,
    label: &str,
) -> String {
    let mut binding_map = naga_old::back::hlsl::BindingMap::default();
    for (_, variable) in module.global_variables.iter() {
        if let Some(binding) = &variable.binding {
            binding_map.insert(
                binding.clone(),
                naga_old::back::hlsl::BindTarget {
                    space: 0,
                    register: binding.binding + if binding.group == 0 { 0 } else { 2 },
                    ..Default::default()
                },
            );
        }
    }
    let options = naga_old::back::hlsl::Options {
        shader_model: naga_old::back::hlsl::ShaderModel::V5_0,
        binding_map,
        fake_missing_bindings: false,
        ..Default::default()
    };
    let mut output = String::new();
    naga_old::back::hlsl::Writer::new(&mut output, &options)
        .write(module, info, None)
        .unwrap_or_else(|error| panic!("failed to generate HLSL for {label}: {error}"));
    output
}

fn write_msl(
    module: &naga_old::Module,
    info: &naga_old::valid::ModuleInfo,
    label: &str,
) -> String {
    let mut resources = naga_old::back::msl::BindingMap::default();
    for (_, variable) in module.global_variables.iter() {
        let Some(binding) = &variable.binding else {
            continue;
        };
        let target = match variable.space {
            naga_old::AddressSpace::Uniform | naga_old::AddressSpace::Storage { .. } => {
                naga_old::back::msl::BindTarget {
                    buffer: Some((binding.binding + if binding.group == 0 { 0 } else { 2 }) as u8),
                    ..Default::default()
                }
            }
            naga_old::AddressSpace::Handle => match module.types[variable.ty].inner {
                naga_old::TypeInner::Image { .. } => naga_old::back::msl::BindTarget {
                    texture: Some(binding.binding.saturating_sub(1) as u8),
                    ..Default::default()
                },
                naga_old::TypeInner::Sampler { .. } => naga_old::back::msl::BindTarget {
                    sampler: Some(naga_old::back::msl::BindSamplerTarget::Resource(0)),
                    ..Default::default()
                },
                ref ty => panic!("unsupported MSL resource type {ty:?} in {label}"),
            },
            space => panic!("unsupported MSL resource space {space:?} in {label}"),
        };
        resources.insert(binding.clone(), target);
    }
    let entry_resources = naga_old::back::msl::EntryPointResources {
        resources,
        sizes_buffer: Some(3),
        ..Default::default()
    };
    let per_entry_point_map = module
        .entry_points
        .iter()
        .map(|entry| (entry.name.clone(), entry_resources.clone()))
        .collect();
    let options = naga_old::back::msl::Options {
        lang_version: (2, 0),
        per_entry_point_map,
        fake_missing_bindings: false,
        ..Default::default()
    };
    naga_old::back::msl::write_string(
        module,
        info,
        &options,
        &naga_old::back::msl::PipelineOptions::default(),
    )
    .map(|(source, _)| source)
    .unwrap_or_else(|error| panic!("failed to generate MSL for {label}: {error}"))
}
