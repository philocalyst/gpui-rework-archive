#!/usr/bin/env python3
"""Offline SQLite oracle for the pinned schema; never a Cargo build step."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sqlite3

PORT = Path(__file__).resolve().parents[1]
SEED = "migrations/20250825234341_insert_liked_songs.sql"
POSITION = "migrations/20260419000000_add_playlist_position.sql"


def generate():
    declared = (PORT / "src/migrations.rs").read_text()
    names = re.findall(r'include_str!\("\.\./([^\"]+)"\)', declared)
    if not names or len(names) != len(set(names)):
        raise ValueError("expected unique, explicitly ordered pinned migrations")
    connection = sqlite3.connect(":memory:")
    connection.execute("PRAGMA foreign_keys=ON")
    hashes = {}
    for name in names:
        data = (PORT / name).read_bytes()
        hashes[name] = hashlib.sha256(data).hexdigest()
        connection.executescript(data.decode())
    objects = connection.execute(
        "SELECT type,name,sql FROM sqlite_schema WHERE sql IS NOT NULL "
        "AND name NOT LIKE 'sqlite_%' ORDER BY "
        "CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 "
        "WHEN 'view' THEN 2 WHEN 'trigger' THEN 3 ELSE 4 END,rowid"
    ).fetchall()
    if connection.execute("PRAGMA foreign_key_check").fetchall():
        raise ValueError("migration oracle has broken foreign keys")
    nonempty = []
    for name, in connection.execute("SELECT name FROM sqlite_schema WHERE type='table'"):
        quoted = '"' + name.replace('"', '""') + '"'
        if connection.execute("SELECT EXISTS(SELECT 1 FROM " + quoted + ")").fetchone()[0]:
            nonempty.append(name)
    if nonempty != ["playlist"]:
        raise ValueError("new seed data needs an explicit seed policy: " + repr(nonempty))
    seed = connection.execute("SELECT id,name,type,position FROM playlist").fetchall()
    if seed != [(1, "Liked Songs", 1, 1)]:
        raise ValueError("pinned seed projection changed: " + repr(seed))
    # Keep the original INSERT and default CURRENT_TIMESTAMP evaluation. The
    # later position UPDATE also runs verbatim, without its obsolete ALTER/index.
    position = (PORT / POSITION).read_text()
    start = position.index("UPDATE playlist\n")
    end = position.index(";", start) + 1
    seed_sql = (PORT / SEED).read_text().strip() + "\n\n" + position[start:end]
    sql = "-- Generated by tools/generate-fresh-schema.py; do not edit.\n"
    sql += "-- Final pinned upstream schema for brand-new databases only.\n\n"
    for kind, name, definition in objects:
        sql += "-- " + kind + ": " + name + "\n" + definition.rstrip(";\n") + ";\n\n"
    sql += "-- Preserve seed INSERT/default expressions, not one oracle's clock.\n"
    sql += seed_sql + "\n"
    metadata = {
        "scope": "Offline standard-library SQLite derivation, not a runtime/build dependency. "
                 "Rust tests compare the result against bundled SQLite replaying these untouched migrations.",
        "sqlite_generator_version": sqlite3.sqlite_version,
        "generator_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "ordered_migrations": hashes,
        "schema_sql_sha256": hashlib.sha256(sql.encode()).hexdigest(),
        "objects": [{"type": kind, "name": name} for kind, name, _ in objects],
        "seed_sources": [SEED, POSITION],
        "seed_policy": "Original INSERT and later position UPDATE preserve runtime timestamp defaults. "
                       "No SQLite internal table is manually created or populated.",
        "version_policy": "Fresh schema1 creation only. Existing schema1 libraries reopen unchanged. "
                          "Unknown versions are rejected; future upgrades need an explicit policy.",
    }
    return {PORT / "schema/fresh.sql": sql,
            PORT / "FRESH-SCHEMA.json": json.dumps(metadata, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generate().items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit("stale generated file: " + str(path))
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
