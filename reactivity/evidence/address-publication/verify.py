from pathlib import Path
import json,hashlib,subprocess,tempfile,shutil,re
r=Path(__file__).parent
m=json.loads((r/'MANIFEST.json').read_text())
assert set(m)=={p.relative_to(r).as_posix() for p in r.rglob('*') if p.is_file() and p.name!='MANIFEST.json'}
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
for n,h in m.items():assert sha(r/n)==h,n
transform=(r/'frozen/reactivity/crates/gpu/src/renderer/address_lab.rs').read_text().split('pub fn shader_source() -> String {',1)[1].split('impl GpuContext',1)[0]
# Extract the three frozen exact literal replacements, in source order. This
# verifies actual generated bytes, not a second hand-maintained shader model.
literal=r'"(?:\\.|[^"\\])*"'
ops=[]
pattern=r'replace_once\(\s*&mut source,\s*('+literal+r'),\s*(r#"(.*?)"#|'+literal+r'),\s*\);'
for match in re.finditer(pattern,transform,re.S):
 new=match.group(3) if match.group(2).startswith('r#') else json.loads(match.group(2))
 ops.append((match.start(),json.loads(match.group(1)),new))
pattern=r'source = source.replacen\(\s*('+literal+r'),\s*r#"(.*?)"#,\s*1,\s*\);'
for match in re.finditer(pattern,transform,re.S):ops.append((match.start(),json.loads(match.group(1)),match.group(2)))
assert len(ops)==3
for lane,driver in [('first','gate-first.py'),('corrected','gate-corrected.py'),('admitted','gate-admitted.py'),('bounded','gate-bounded.py'),('accounted','gate.py')]:
 p=r/'raw'/lane
 expected={'build':101} if lane=='first' else {'build':0,'trace':0,'clippy':101 if lane=='corrected' else 0}
 if lane in ['bounded','accounted']:expected.update({'bounds-build':0,'bounds':0,'bounds-clippy':0})
 for gate,code in expected.items():assert json.loads((p/(gate+'.status.json')).read_text())['exit']==code
 assert json.loads((p/'guard.json').read_text())==[]
 assert json.loads((p/'driver.json').read_text())['sha256']==sha(r/'raw'/driver)
 if lane in ['admitted','bounded','accounted']:assert json.loads((p/'overall.json').read_text())['decision']=='PASSED'
 if lane=='first':continue
 a=json.loads((p/'artifact.json').read_text());elf=Path(a['preserved']).read_bytes();assert hashlib.sha256(elf).hexdigest()==a['sha256'];assert len(elf)==a['bytes'] and a['cargo_fresh'] is False
 shader=(p/'ui.wgsl').read_bytes()
 for q in json.loads((p/'shaders.json').read_text()).values():assert hashlib.sha256(shader).hexdigest()==q['sha256'] and elf[q['elf_offset']:q['elf_offset']+q['bytes']]==shader
 alternative=shader.decode()
 for _,old,new in sorted(ops):
  assert old in alternative;alternative=alternative.replace(old,new,1)
 assert alternative.encode()==(p/'trace/alternative.wgsl').read_bytes()
 for _,_,new in ops:assert new.encode() in elf
 if lane in ['bounded','accounted']:
  a=json.loads((p/'bounds-artifact.json').read_text());b=Path(a['preserved']);assert sha(b)==a['sha256'] and b.stat().st_size==a['bytes'] and not a['cargo_fresh']
assert (r/'source.txt').read_bytes()==(r/'raw/accounted/source.txt').read_bytes()
inputs=json.loads((r/'raw/accounted/inputs-before.json').read_text())
for p in (r/'frozen').rglob('*'):
 if p.is_file():assert sha(p)==inputs[p.relative_to(r/'frozen').as_posix()]
with tempfile.TemporaryDirectory(prefix='gpui-address-verify-') as t:
 t=Path(t);shutil.copy2(r/'raw/analyze.py',t/'analyze.py')
 subprocess.run(['python3',str(t/'analyze.py'),str(r/'raw/accounted')],check=True)
 assert (t/'analysis.json').read_bytes()==(r/'raw/analysis.json').read_bytes()
print(f'verified {len(m)} files, five preserved cohorts, actual shader transformations, 63+129 GPU encoding comparisons; inherited cross-backend gate FAILED; no timing claim')
