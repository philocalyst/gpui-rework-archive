from pathlib import Path
import json,hashlib,subprocess,tempfile,shutil
r=Path(__file__).parent
m=json.loads((r/'MANIFEST.json').read_text())
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
assert set(m)=={p.relative_to(r).as_posix() for p in r.rglob('*') if p.is_file() and p.name!='MANIFEST.json'}
for n,h in m.items():assert sha(r/n)==h,n
b=r/'raw/build-first';c=r/'raw/campaign'
for g in ['build','clippy']:assert json.loads((b/(g+'.status.json')).read_text())['exit']==0
assert json.loads((b/'guard.json').read_text())==[] and json.loads((c/'guard.json').read_text())==[]
assert json.loads((b/'overall.json').read_text())['decision'].startswith('PASSED')
a=json.loads((b/'artifact.json').read_text());elf=Path(a['preserved']).read_bytes();assert hashlib.sha256(elf).hexdigest()==a['sha256'] and len(elf)==a['bytes'] and not a['cargo_fresh']
assert a==json.loads((c/'artifact.json').read_text())
shader=(b/'ui.wgsl').read_bytes()
for s in json.loads((b/'shaders.json').read_text()).values():assert hashlib.sha256(shader).hexdigest()==s['sha256'] and elf[s['elf_offset']:s['elf_offset']+s['bytes']]==shader
assert json.loads((b/'driver.json').read_text())['sha256']==sha(r/'raw/build.py')
d=json.loads((c/'driver.json').read_text());assert d['sha256']==sha(r/'run.py') and d['analysis_sha256']==sha(r/'analyze.py')
bi=json.loads((b/'inputs-before.json').read_text());ci=json.loads((c/'inputs-before.json').read_text());assert all(ci.get(n)==h for n,h in bi.items())
for p in (r/'frozen').rglob('*'):
 if p.is_file():assert sha(p)==bi[p.relative_to(r/'frozen').as_posix()]
assert (r/'compiled-source.txt').read_bytes()==(b/'source.txt').read_bytes();assert (r/'campaign-source.txt').read_bytes()==(c/'source.txt').read_bytes()
order=json.loads((c/'order.json').read_text());expected=[];modes=['raw','relocation','relative','stable'];families=['keyed4','unkeyed4','keyed256','reorder256','mixed','resources']
for block in range(6):
 sequence=modes[block%4:]+modes[:block%4]
 for family in families:
  for direction,seq in [('forward',sequence),('reverse',list(reversed(sequence)))]:
   for mode in seq:expected.append(dict(block=block,family=family,direction=direction,mode=mode))
assert order==expected
alternative=(r/'raw/parent-alternative.wgsl').read_bytes();assert (r/'raw/parent-ui.wgsl').read_bytes()==shader
for status in json.loads((c/'completed.json').read_text()):
 if status['mode']!='raw':assert (c/status['path']/'alternative.wgsl').read_bytes()==alternative
# The unchanged parent transformer and actual generated bytes are also frozen;
# verified parent publication dossier supplies the three exact replacement proof.
with tempfile.TemporaryDirectory(prefix='gpui-address-cost-verify-') as t:
 t=Path(t);shutil.copy2(r/'analyze.py',t/'analyze.py')
 subprocess.run(['python3',str(t/'analyze.py'),str(c)],check=True,stdout=subprocess.DEVNULL)
 assert (t/'analysis.json').read_bytes()==(r/'raw/analysis.json').read_bytes()
x=json.loads((r/'raw/analysis.json').read_text());assert x['processes']==288 and x['measured_updates']==110592
assert {k:v['verdict'] for k,v in x['verdicts'].items()}=={'relative':'NOT ADMITTED','stable':'NOT ADMITTED'}
assert x['verdicts']['relative']['storage'] and not x['verdicts']['stable']['storage']
print(f'verified {len(m)} files, 288 processes, 110592 timed updates, original final pixel oracle and frozen paired gates; relative/stable NOT ADMITTED')
